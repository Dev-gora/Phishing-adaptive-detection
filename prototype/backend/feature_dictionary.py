def dictionary(columns: Iterable[str]) -> List[dict]:
    """Describe every feature the dataset actually contains."""
    import url_features

    served = set(url_features.DESCRIPTIONS)
    rows = []
    for name in columns:
        rows.append(
            {
                "name": name,
                "description": DESCRIPTIONS.get(name, ""),
                "group": GROUPS.get(name, "Other"),
                "computed_live": name in served,
            }
        )
    return rows
